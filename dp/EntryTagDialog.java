    /**
     * Create a new tag.
     *
     * Get a tag from user, store it in the db and attach it to the current entry. This applies only
     * if a new entry is to be created.
     * 
     * @param evt
     */
    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
       // TODO add your handling code here:
       // Add a new tag to the db, and attach it to the entry ..
       // Start ... Firt figure out the max.
       if(entry.getDB()!=null)
       {
            int tagID = 0;
            try
            {
               java.sql.Statement stmt = entry.getDB().createStatement();
               java.sql.ResultSet result = stmt.executeQuery("select max(tagid) from ztags");
               result.next();
               tagID = result.getInt(1);
               tagID = tagID + 1;
               stmt.close();
               //jTextField1.setText(String.valueOf(tagID));
               java.sql.PreparedStatement ps =
                       entry.getDB().prepareStatement("insert into ztags values(?, ?)");
               ps.setInt(1, tagID);
               ps.setString(2, jTextField1.getText().replace(',', ' '));
               ps.execute();
               ps.close();
               ps = entry.getDB().prepareStatement("insert into ztagmember values (?,?,?)");
               ps.setInt(1, tagID);
               ps.setDate(2,
                       java.sql.Date.valueOf(projx.ZeebUtil.formatDate(entry.getID().getDate())));
               ps.setInt(3, entry.getID().getNumber());
               ps.execute();
               ps.close();
               updateEntryTable(tagID, jTextField1.getText().replace(',', ' '));
               jTextField1.setText("");

               this.panel.showTags();
            }
            catch (java.sql.SQLException e){ jTextField1.setText(e.getMessage());}

       }
    }//GEN-LAST:event_jButton2ActionPerformed

    /**
     * Attach an existing tag to the current entry.
     *
     * Attach tags that have been added to the the database to the current entry.
     * First get the tag, selection is made by the user on the tag table. Then call
     * addExistingTagsToEntry (projx.Tag tag).
     *
     * @param evt
     */
    private void buttonAddExistingTagActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonAddExistingTagActionPerformed
       // TODO add your handling code here:
       projx.Tag tag;

       try
       {
       tag = (projx.Tag)
            tableTags.getModel().getValueAt(tableTags.getSelectedRow(), tableTags.getSelectedColumn());
       addExistingTagsToEntry(tag);
       }
       catch (java.lang.ArrayIndexOutOfBoundsException e)
       {}
    }//GEN-LAST:event_buttonAddExistingTagActionPerformed

    /**
     * Actually attach the tag to the entry.
     *
     * 1. Store the record in the db.
     * 2. Show the new tag in the tag table (table which shows tags attached to the current entry)
     * 3. Update the text display panel.
     *
     * @param tag The tag to add.
     */
    private void addExistingTagsToEntry (projx.Tag tag)
    {
         try
            {
               java.sql.PreparedStatement ps =
                       entry.getDB().prepareStatement("insert into ztagmember values (?,?,?)");
               ps.setInt(1, tag.getID());
               ps.setDate(2,
                       java.sql.Date.valueOf(projx.ZeebUtil.formatDate(entry.getID().getDate())));
               ps.setInt(3, entry.getID().getNumber());
               ps.execute();
               ps.close();
               updateEntryTable(tag);
               this.panel.showTags();
            }
            catch (java.sql.SQLException e){ jTextField1.setText(e.getMessage());}
    }

    /**
     * Update the table (tableEntry) display, if a new tag is created.
     *
     * @param i The new tag's id
     * @param t The tag.
     */
    public void updateEntryTable(int i, String t)
    {
         javax.swing.table.DefaultTableModel tm =
                 (javax.swing.table.DefaultTableModel) tableEntry.getModel();
         projx.Tag[] tg = new projx.Tag[1];
         tg[0] = new projx.Tag(i, t);
         tm.addRow(tg);
    }

    /**
     * Update the table (tableEntry) display, if we're adding existing tag.
     *
     * @param tag The tag.
     */
    public void updateEntryTable (projx.Tag tag)
    {
      updateEntryTable(tag.getID(), tag.toString());
    }

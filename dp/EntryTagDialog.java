    /**
     * Fill the table which contains tags associated with this entry.
     */
    private void populateEntryTagTable ()
    {
         // Get tag list from entry, and populate [tableEntry]
         int i = 0;
         while (i < entry.getTags().size())
         {
            javax.swing.table.DefaultTableModel tm =
                    (javax.swing.table.DefaultTableModel) tableEntry.getModel();
            projx.Tag[] tg = new projx.Tag[1];
            tg[0] = (projx.Tag) entry.getTags().get(i);
            tm.addRow(tg);
            i++;
         }
         // Grab stored tag from the DB and fill the [tableTag], that is not difficult
         // populateTagTable();
    }

    /**
     * Fill the table which contains all stored tags.
     */
    private void populateTagTable ()
    {
         try
         {
            javax.swing.table.DefaultTableModel tm =
                    (javax.swing.table.DefaultTableModel) tableTags.getModel();
            java.sql.PreparedStatement ps =
            entry.getDB().prepareStatement("select * from ztags");
            java.sql.ResultSet result = ps.executeQuery();
            ps.close();
            projx.Tag[] tg = new projx.Tag[1];
            while (result.next())
            {
               tg[0] = new projx.Tag(result.getInt(1), result.getString(2));
               tm.addRow(tg);
            }

         }
         catch(java.sql.SQLException e){}
    }

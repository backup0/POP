    /**
     * Load records from the bookmark table.
     *
     * The method connects to the database, and load all bookmark records from the table which
     * stores those records, then call the populateTable method.
     */
    private void loadBookmark ()
    {
        java.sql.PreparedStatement ps = null;
        java.sql.ResultSet result = null;
        String query =
                "select dBookmark.id, dailycat.catname from dBookmark, dailycat where dBookmark.cat = dailycat.catid";

        try
        {
            ps = db.prepareStatement(query);
            result = ps.executeQuery();
            ps.close();
            populateTable(result);
        }
        catch (java.sql.SQLException e){}
    }

    /**
     * Fill the table with list of bookmarked entries.
     *
     * @param r Result set containing bookmark records.
     */
    private void populateTable (java.sql.ResultSet r)
    {
         javax.swing.table.DefaultTableModel tm =
                 (javax.swing.table.DefaultTableModel) table.getModel();
         Object[] item = new Object[2];
         tm.setRowCount(0);
         try
         {
              while (r.next())
              {
                  item[0] = projx.ZeebUtil.formatDate(r.getDate(1));
                  item[1] = r.getString(2);
                  tm.addRow(item);
              }
         }
         catch (java.sql.SQLException e)
         {
               javax.swing.JOptionPane.showMessageDialog(null, e.getMessage());

         }

    }

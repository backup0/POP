    private java.util.Date getDate (
            javax.swing.JTextField dayField,
            javax.swing.JComboBox monthField,
            javax.swing.JTextField yearField)
    {
         // We need to format the goddamn thing ... Great
         int day;
         int month;
         int year;
         // first we need a calendar
         java.util.Calendar calendar = java.util.Calendar.getInstance();
         // thenwe reset the calendar
         calendar.clear();
         // .. Next figure out if .. all fields are properly field, otherwise we can't do anything
         // To do that we need to get the data and such
         try
         {
            day = Integer.parseInt(dayField.getText());
            year = Integer.parseInt(yearField.getText());
         }
         catch (java.lang.NumberFormatException e)
         {  return null;}
         // the month thing ...
         month = monthField.getSelectedIndex() - 1;
         if (month < 0)
            return null;
         // Set the date ... and such .. .. No, set the year and the month
         calendar.set(java.util.Calendar.MONTH, month);
         calendar.set(java.util.Calendar.YEAR, year);
         // See if the day part isn't higher than max -- well, 32 isn't aceptable, so is 31, and 29
         // sometimes
         if (day > calendar.getActualMaximum(java.util.Calendar.DAY_OF_MONTH))
         {
            return null;
         }
         else
         {
            calendar.set(java.util.Calendar.DAY_OF_MONTH, day);
         }
         return calendar.getTime();
    }


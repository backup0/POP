    /**
     * Load entry into a linked list
     *
     * The purpose of this method is to load entries into a linked list for further processing.
     * The entries come from the database. Since the entries may create a tree structure, the method
     * has to be recursively called, and a new list is created every time it is called, hence a list
     * may contain lists, and not just entries.
     *
     * @param list The list to be populated
     * @param entry Result from the db.
     */
    private void populateEntryList (projx.EntryLinkedList list, java.sql.ResultSet entry)
    {

       // Now let's start loading them into the linked list
       try
       {
          do
          {
             // We need to traverse through the list .. Ok?
             // now set up some variables we're going to use later
             // Get the entry's id
             projx.ZeebID id = new projx.ZeebID(entry.getDate("edate"), entry.getInt("enumb"));
             // get the entry's parent's id
             projx.ZeebID pID =
                     new projx.ZeebID(entry.getDate("eparentdate"), entry.getInt("eparentnumb"));
             // Set up the arguments we're going to use in the query
             // The id, so .. the query will retrieve entries which are children of this entry.
             String pDate = "= '" + projx.ZeebUtil.formatDate(id.getDate()) + "'";
             String pNum = "= " + String.valueOf(id.getNumber());
             // We create an entry .. and load the data
             projx.FFEntry eItem = new projx.FFEntry
                     (this.db, // The databse
                     id, // This entry's id
                     entry.getString("ename"), // The name
                     entry.getString("emnote"), // The note
                     (byte) entry.getInt("etype"), // Type
                     pID, // Parent's id
                     entry.getString("eicon") // icon
                     );
             //projx.FFEntry entryItem = new projx.FFEntry(projx.FFEntry.NEW);
             // --
             //entryItem.setID(entry.getDate("edate"), entry.getInt("enumb"));
             //entryItem.setName(entry.getString("ename"));
             //entryItem.setIcon("Fuck icon");
             //entryItem.setNote("Fuck note as for now");
             //entryItem.setContent(ll);
             // And other stuff I suppose ...

             // Now let's load another set of entries, this entries children if they exist.
             java.sql.ResultSet result = loadEntry(pDate, pNum);
             // Ok, that was pointless ...
             // Do the useful stuff
             if (result == null) // This means this entry has no children
             {
                // So we load the entry into the list .. as in, yeah we have to do that.
                // So, what do we do again?
                // Add item to the list ...
                list.add(eItem);
             }
             else // This means there's at least one children, and so we need to keep on going, we
             // need to load the children groups.
             {
                // So create another list ...
                projx.EntryLinkedList newList = new projx.EntryLinkedList();
                // Add entry to the list .. This is the major thing
                newList.setEntry(eItem);
                // Attach the list to an existing list
                list.add(newList);
                // Populate the new list with .. stuff
                populateEntryList (newList, result);
             }
             
          } while (entry.next());
       }
       catch (java.sql.SQLException e)
       {
       }
    }

    /**
     * Load entries from the database.
     *
     * @param date Date portion of the parent's id.
     * @param num  Number portion of the parent's id.
     * @return Result set containing the entries.
     */
    private java.sql.ResultSet loadEntry (String date, String num)
    {
       java.sql.Statement statement;
       String query = "(select * from zfentry where ";
       query = query + "eparentdate " + date + " and "; // where eparentdate = null and eparentnumb = null)";
       query = query + "eparentnumb " + num + ")";
       java.sql.ResultSet result = null;

       try
       {
          statement = db.createStatement();
          result = statement.executeQuery(query);
          if(!result.next())
             result = null;
          statement.close();
       }
       catch (java.sql.SQLException e)
       {
            javax.swing.JOptionPane.showMessageDialog(this,
                    zDB + "\n" +e.getMessage());
       }
       return result;
    }


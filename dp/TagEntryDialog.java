    private void getTags ()
    {
       java.sql.PreparedStatement ps;
       java.sql.ResultSet result;
       java.util.LinkedList tagList = new java.util.LinkedList<projx.Tag>();
       String query = "select * from ztags";

       try
       {
               ps = db.prepareStatement(query);
               result = ps.executeQuery();
               while (result.next())
               {
                  tagList.add(new projx.Tag(result.getInt(1), result.getString(2)));
               }
               populateTagList(tagList);
       }
       catch (java.sql.SQLException e)
       {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
       }
    }

    private void populateTagList(java.util.LinkedList tags)
    {
         listTag.setModel(new javax.swing.DefaultListModel());
         javax.swing.DefaultListModel lm =
                 (javax.swing.DefaultListModel) listTag.getModel();
         projx.Tag tag;

         lm.clear();
         int i = 0;
         while (i < tags.size())
         {

            tag = (projx.Tag) tags.get(i);
            lm.addElement(tag);
            i++;
         }
    }



    /**
     * Load the content of the entry.
     *
     * The FFEntry instance doesn't hold the actual content, just information about the entry to
     * load the content, it has to be retrieved from the db.
     */
    private void loadEntry()
    {
       // get the node
       Object so = tree.getSelectedNode();
       try{
         if (so.getClass().getName().matches("projx.FFEntry")) // if it's an entry then just load it
         {
               entry = (projx.FFEntry) so; // Now we have the entry - we need to load the actual content.
               jSplitPane3.setRightComponent(new EntryTextPanel(entry));
               jSplitPane3.setDividerLocation(180);
               loadNotes();
          }
         else if (so.getClass().getName().matches("projx.EntryLinkedList"))
         {
               projx.EntryLinkedList ll = (projx.EntryLinkedList) so;
               entry = ll.getEntry();
               jSplitPane3.setRightComponent(new EntryTextPanel(entry));
               jSplitPane3.setDividerLocation(180);
               loadNotes();
         }
          else
         {
               javax.swing.JOptionPane.showMessageDialog(this, "Neither entry not linkedList");
         }
         }
         catch (java.lang.NullPointerException npe) {}
    }



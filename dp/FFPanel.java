    /**
     *
     * Prepare to create a new entry.
     *
     * To create a new entry we need to know which node on the tree is currently selected. The node
     * will be the new entry's parent. This method figures out which node is currently selected.
     * It then show the CreateEntryDialog and that dialog takes care of the rest.
     *
     * @param evt
     */
    private void buttonCreateEntryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buttonCreateEntryActionPerformed
       // TODO add your handling code here:
       // We create an entry here ... Grab data from, say a .. Dialog and get this done.  ..
       // We need to know to what node this new entry should be attached to .. So, we need to
       // acces the tree object. But first create the nodes
       javax.swing.tree.DefaultMutableTreeNode pNode = null;
       // We also need the treepath
       javax.swing.tree.TreePath tp = null;
       // let's figure out which one's selected ..
       tp = jTree1.getSelectionPath();
       // Now that we have the path .. Check if it's null, if it is then none is selected .. hence
       // we'll be working wit the root node...
       if (tp == null) // root node
       {
            pNode = (javax.swing.tree.DefaultMutableTreeNode) jTree1.getModel().getRoot();
       }
       else // if it's not the root
       {
            pNode = (javax.swing.tree.DefaultMutableTreeNode) tp.getLastPathComponent();
       }
       // Now that we have our node - Wel'll be attaching the new entry here .. Yeah .. Onto this
       // node .. First we create the dialog, it'll take care of thr rest
       CreateEntryDialog dg = new CreateEntryDialog(null, true, this, pNode);
       // Make it show
       dg.setVisible(true);
    }//GEN-LAST:event_buttonCreateEntryActionPerformed

    /**
     * Create the new entry and update the tree.
     *
     * @param name The name of the new entry.
     * @param note Notes about the entry.
     * @param type Type of entry.
     * @param parent The entry's parent.
     * @param icon Icon.
     * @param pnode The parent node.
     */
    public void extCreateEntry(
            String name,
            String note,
            byte type,
            projx.ZeebID parent,
            String icon,
            javax.swing.tree.DefaultMutableTreeNode pnode
            )
    {
       // Now let's create the actual entry ..
       projx.FFEntry newEntry =
               new projx.FFEntry(entry.getDB(), name, note, type, parent, icon);
       javax.swing.tree.DefaultTreeModel tm =
               (javax.swing.tree.DefaultTreeModel) jTree1.getModel();
       javax.swing.tree.DefaultMutableTreeNode newNode = 
               new javax.swing.tree.DefaultMutableTreeNode(newEntry);
       tm.insertNodeInto(newNode, pnode, pnode.getChildCount());
       jTree1.scrollPathToVisible(new javax.swing.tree.TreePath(newNode.getPath()));
    }


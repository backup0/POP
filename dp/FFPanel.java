    /**
     * Load notes attached to this entry.
     */
    private void loadNotes ()
    {
         java.sql.PreparedStatement ps = null;
         javax.swing.DefaultListModel lm =
                 (javax.swing.DefaultListModel) listNotes.getModel();
         // have to clear the display, have to clear the display ..
         lm.clear();
         try
         {
            ps = db.prepareStatement("select nid, text from ffnotes where edate = ? and enumb = ?");
            ps.setDate(1, java.sql.Date.valueOf(projx.ZeebUtil.formatDate(entry.getID().getDate())));
            ps.setInt(2, entry.getID().getNumber());
            java.sql.ResultSet rs = ps.executeQuery();
            while (rs.next())
            {
               lm.addElement(new projx.ZeebNotes(rs.getString(2), rs.getInt(1)));
            }
         }
         catch (java.sql.SQLException e)
         {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
         }

    }

    /**
     * Edit selected note.
     */
    private void editNote ()
    {
       javax.swing.DefaultListModel lm =
               (javax.swing.DefaultListModel) listNotes.getModel();
       projx.ZeebNotes note = (projx.ZeebNotes ) listNotes.getSelectedValue();
       String newNote = javax.swing.JOptionPane.showInputDialog("Note", note.toString());
       if (newNote != null)
       {
       try
       {
           java.sql.PreparedStatement ps =
                   db.prepareStatement("update ffnotes set text = ? where nid = ? ");
           ps.setInt(2, note.getId());
           ps.setString(1, newNote);
           ps.execute();
           loadNotes();
       }
       catch (java.sql.SQLException e)
       {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
       }
       }
    }

    /**
     * Delete selected note from this entry.
     */
    private void removeNote ()
    {
       javax.swing.DefaultListModel lm =
               (javax.swing.DefaultListModel) listNotes.getModel();
       projx.ZeebNotes note = (projx.ZeebNotes ) listNotes.getSelectedValue();
       javax.swing.JOptionPane.showMessageDialog(this, note);

       try
       {
           java.sql.PreparedStatement ps =
                   db.prepareStatement("delete from ffnotes where nid = ?");
           ps.setInt(1, note.getId());
           ps.execute();
           loadNotes();
       }
       catch (java.sql.SQLException e)
       {
            javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());
       }
    }

    /**
     * Attach a new note to this entry.
     */
    private void addNote ()
    {
         String note = javax.swing.JOptionPane.showInputDialog("Note to add", "What to add");
         java.sql.PreparedStatement ps = null;
         try
         {
            ps = db.prepareStatement("insert into ffnotes(edate, enumb, text) values(?, ?, ?)");
            ps.setDate(1, java.sql.Date.valueOf(projx.ZeebUtil.formatDate(entry.getID().getDate())));
            ps.setInt(2, entry.getID().getNumber());
            ps.setString(3, note);
            ps.execute();
            loadNotes();
         }
         catch (java.sql.SQLException e)
         {  javax.swing.JOptionPane.showMessageDialog(this, e.getMessage());}

    }

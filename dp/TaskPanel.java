    /**
     * Store the task.
     * @param evt
     */
    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
       // TODO add your handling code here:
       java.util.Calendar start = java.util.Calendar.getInstance();
       java.util.Calendar end = java.util.Calendar.getInstance();

       newTask.setTitle(textTitle.getText());
       newTask.setDescription(textDesc.getText());

       if (newTask.getStartDate() != null && newTask.getDueDate() != null)
       {
          start.setTime(newTask.getStartDate());
          end.setTime(newTask.getDueDate());
          if (start.after(end))
          {
              javax.swing.JOptionPane.showMessageDialog(this, "Due date should not be earlier than start date!");
          }
          else
          {
               if (chkCarryOver.isSelected())
                  newTask.setCarryOver(Boolean.TRUE);
               else
                  newTask.setCarryOver(Boolean.FALSE);

               taskManager.storeTask(newTask);
          }
       }
       else
       {
            if (newTask.getDueDate() != null)
            {
               if (chkCarryOver.isSelected())
                  newTask.setCarryOver(Boolean.TRUE);
               else
                  newTask.setCarryOver(Boolean.FALSE);
            }
               taskManager.storeTask(newTask);
       }
    }//GEN-LAST:event_jButton4ActionPerformed


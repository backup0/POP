    /**
     * Fill table with tasks.
     */
    private void loadTasks ()
    {
        int i = 0;
        Object[] cols = new Object[4];
        projx.Task task = null;
        javax.swing.table.DefaultTableModel tm =
                (javax.swing.table.DefaultTableModel) table.getModel();
        tm.setRowCount(0);
        java.text.SimpleDateFormat sdf =
                new java.text.SimpleDateFormat("MMM d, yyyy");
        // Get the items ...
        while (i < taskList.size())
        {
            task = (projx.Task) taskList.get(i);
            cols[0] = task;
            cols[1] = task.getTitle();
            // cols[2]
            if (task.getStartDate() == null)
               cols[2] = "--";
            else
               cols[2] = sdf.format(task.getStartDate());
            // cols[3]
            if (task.getDueDate() == null)
               cols[3] = "--";
            else
               cols[3] = sdf.format(task.getDueDate());
            tm.addRow(cols);
            i++;
        }
    }

    /**
     * Show tags associated with this entry.
     *
     * Get the tags from the database, and show them. We need to reload the tag from the db every
     * time this method is called, since the display is updated every time a new tag is attached or
     * one is removed.
     */
    public final void showTags()
    {
         // Great we need a nested query here ...
         String query =
                 "select * from ztags where tagid in (select tag from ztagmember where edate = ? and enumb = ?)";
         labelTag.setText("");
         try
         {
            java.sql.PreparedStatement ps = entry.getDB().prepareStatement(query);
            ps.setDate(1, java.sql.Date.valueOf(projx.ZeebUtil.formatDate(entry.getID().getDate())));
            ps.setInt(2, entry.getID().getNumber());
            java.sql.ResultSet result = ps.executeQuery();
            ps.close();
            java.util.LinkedList ll = new java.util.LinkedList();
            while (result.next())
            {
               // Add the item to the list
               ll.add(new projx.Tag(result.getInt("tagid"), result.getString("tag")));
               labelTag.setText(labelTag.getText() + result.getString("tag") + ", ");
            }
            // attch the list to the entry
            entry.attachTags(ll);
         }
         catch (java.sql.SQLException e){}

    }
